"""Turn the Prolog solver into data for the web GUI (docs/data/megaminx.json).

Reads, from "Megaminx Human Algorithm":
  megaminx_rotations.pl  basic moves as 132-sticker permutations, special moves as move sequences
  megaminx_goals.pl      the 116 stage goals as sticker patterns ("_" = any colour)
  megaminx_algorithm.pl  the moves allowed in each stage (cand/2) and the last stage (stage([],N,_))
  mytest.pl              the demo scramble
Nothing is re-implemented by hand: the GUI's solver runs on exactly these facts.
"""
import json, re, sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = root / "Megaminx Human Algorithm"

def strip_comments(text):
    return "\n".join(re.sub(r"%.*", "", line) for line in text.splitlines())

def terms(body):
    """Comma-separated top-level items of a megaminx(...) argument list."""
    return [t.strip() for t in body.split(",")]

rot = strip_comments((src / "megaminx_rotations.pl").read_text(encoding="utf-8"))
moves = {}
for name, a, b in re.findall(r"mov\(\s*(\w+)\s*,\s*megaminx\(([^)]*)\)\s*,\s*megaminx\(([^)]*)\)\s*\)\s*\.", rot):
    before, after = terms(a), terms(b)
    assert len(before) == len(after) == 132, (name, len(before), len(after))
    index = {v: i for i, v in enumerate(before)}
    # after[i] is the variable that was at index[...] before: new_state[i] = old_state[perm[i]]
    moves[name] = [index[v] for v in after]
specials = {}
for name, seq in re.findall(r"mov\(\s*(sp\d+)\s*,\s*X\s*,\s*Y\s*\)\s*:-\s*move_sequence\(\s*\[([^\]]*)\]", rot):
    specials[name] = [s.strip().replace(" ", "") for s in seq.split(",")]

goals_txt = strip_comments((src / "megaminx_goals.pl").read_text(encoding="utf-8"))
goals = {}
for n, body in re.findall(r"get_goal\(\s*(\d+)\s*,\s*megaminx\(([^)]*)\)\s*\)\s*\.", goals_txt):
    n = int(n)
    if n in goals:
        continue  # Prolog uses the first clause; the solver never backtracks past it
    items = terms(body)
    assert len(items) == 132, (n, len(items))
    goals[n] = [t.strip('"') if t != "_" else None for t in items]

# Goal 115 is a rule: get_goal(115, megaminx(Vars...)) :- [W1, R9, G1] = [...]; ...
# Prolog reads "A = X; Y; Z, B = ..." as one big disjunction ("," binds tighter than ";"), so when the
# goal is fetched its first branch succeeds at once and binds only W1, R9 and G1. That is the goal the
# original program searches for, so it is the goal used here.
for n, head, body in re.findall(r"get_goal\(\s*(\d+)\s*,\s*megaminx\(([^)]*)\)\s*\)\s*:-(.*?)\.\s*\n", goals_txt, re.S):
    n = int(n)
    if n in goals:
        continue
    names = terms(head)
    first = re.search(r"\[([^\]]*)\]\s*=\s*\[([^\]]*)\]", body)
    pattern = [None] * 132
    for var, val in zip(terms(first.group(1)), terms(first.group(2))):
        pattern[names.index(var)] = val.strip('"')
    goals[n] = pattern

alg = strip_comments((src / "megaminx_algorithm.pl").read_text(encoding="utf-8"))
cand = {int(n): [m.strip() for m in lst.split(",") if m.strip()] for n, lst in re.findall(r"cand\(\s*(\d+)\s*,\s*\[([^\]]*)\]\s*\)\s*\.", alg)}
# A stage with no cand/2 clause (stage 66: line 83 repeats cand(65, ...)) has no moves to try in Prolog,
# so it passes only if the cube already matches its goal.
for n in range(1, 200):
    cand.setdefault(n, [])
last = int(re.search(r"stage\(\s*\[\]\s*,\s*(\d+)\s*,", alg).group(1)) - 1

test = strip_comments((src / "mytest.pl").read_text(encoding="utf-8"))
scramble = [s.strip().replace(" ", "") for s in re.search(r"move_sequence\(\s*\[([^\]]*)\]", test).group(1).split(",")]

colours = ["W", "G", "R", "B", "Y", "Pr", "H", "Pi", "L", "O", "T", "Gr"]
faces = ["Up", "Left", "Front", "Right", "Back Right", "Back Left", "Down Left", "Down Right", "Back Down Right", "Back", "Back Down Left", "Down"]
data = {"source": "generated by tools/extract_prolog.py from the Prolog solver", "colours": colours, "faces": faces,
        "moves": moves, "specials": specials, "goals": {str(k): goals[k] for k in sorted(goals) if k <= last},
        "candidates": {str(k): cand[k] for k in sorted(cand) if k <= last}, "lastStage": last, "demoScramble": scramble}
out = root / "docs" / "data" / "megaminx.json"
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text(json.dumps(data, separators=(",", ":")), encoding="utf-8")
print(f"{len(moves)} moves, {len(specials)} specials, {len(data['goals'])} goals, {len(data['candidates'])} stages, last {last}, scramble {len(scramble)} -> {out}")
